import assert from "node:assert/strict";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import sharp from "sharp";
import type { AssetManifest } from "../src/engine/types";

async function main() {
  const root = "public/projects/ivans-escape/illustrated/pass02";
  await mkdir(`${root}/layers`, { recursive: true });
  const assets: AssetManifest = {},
    sources = [];
  const save = async (id: string, pixels: Buffer, alpha = false) => {
    const path = `${root}/layers/${id}.png`;
    await sharp(pixels).png().toFile(path);
    const meta = await sharp(path).metadata();
    assert.equal(meta.width, 2560);
    assert.equal(meta.height, 1440);
    assets[id] = {
      id,
      src: path.slice(7),
      kind: "image",
      width: 2560,
      height: 1440,
      alpha,
    };
  };
  const mask = (d: string) =>
    Buffer.from(
      `<svg width="2560" height="1440"><path d="${d}" fill="white"/></svg>`,
    );
  const masked = async (plate: Buffer, d: string) =>
    sharp(plate)
      .ensureAlpha()
      .composite([{ input: mask(d), blend: "dest-in" }])
      .png()
      .toBuffer();
  for (const name of [
    "assigned",
    "awakening",
    "sprint",
    "edge",
    "leap-hero",
    "outside-hero",
    "street",
    "corridor",
    "boundary",
    "outside",
  ]) {
    const path = `${root}/source/${name}.png`,
      source = await sharp(path).metadata();
    const plate = await sharp(path)
      .resize(2560, 1440, { fit: "cover" })
      .png()
      .toBuffer();
    const id = ["street", "corridor", "boundary", "outside"].includes(name)
      ? name
      : `key-${name}`;
    await save(id, plate);
    sources.push({
      name,
      path,
      nativeWidth: source.width,
      nativeHeight: source.height,
      sha256: createHash("sha256")
        .update(await readFile(path))
        .digest("hex"),
      note: "Built-in imagegen, original project inputs only; runtime normalization is not added source detail.",
    });
    if (name === "corridor") {
      await save("corridor-ground", plate);
      for (let i = 0; i < 12; i++)
        await save(
          `facade-${i}`,
          await masked(
            plate,
            `M${(i * 2560) / 12} 0H${((i + 1) * 2560) / 12 + 1}V1440H${(i * 2560) / 12}Z`,
          ),
          true,
        );
    }
    if (name === "boundary" || name === "corridor") {
      for (const [side, d] of Object.entries({
        left: "M0 0H1280V1440H0Z",
        right: "M1280 0H2560V1440H1280Z",
      }))
        await save(`${name}-${side}`, await masked(plate, d), true);
    }
    if (name === "boundary") {
      // The floor begins at the painted horizon, not halfway up the facades.
      await save(
        "boundary-shell",
        await masked(plate, "M0 0H2560V1440L1280 960L0 1440Z"),
        true,
      );
      for (let row = 0; row < 9; row++)
        for (let col = 0; col < 6; col++) {
          const y0 = 960 + (row * 480) / 9,
            y1 = 960 + ((row + 1) * 480) / 9;
          const x = (y: number, c: number) =>
            1280 + ((y - 960) / 480) * (-1280 + (c * 2560) / 6);
          await save(
            `road-${row}-${col}`,
            await masked(
              plate,
              `M${x(y0, col)} ${y0}L${x(y0, col + 1)} ${y0}L${x(y1, col + 1)} ${y1}L${x(y1, col)} ${y1}Z`,
            ),
            true,
          );
        }
    }
  }
  const shadowPath = `${root}/layers/contact-shadow.png`;
  await sharp(
    Buffer.from(
      '<svg width="512" height="128"><defs><radialGradient id="s"><stop stop-color="#07101A" stop-opacity=".7"/><stop offset="1" stop-color="#07101A" stop-opacity="0"/></radialGradient></defs><ellipse cx="256" cy="64" rx="256" ry="64" fill="url(#s)"/></svg>',
    ),
  )
    .png()
    .toFile(shadowPath);
  assets["contact-shadow"] = {
    id: "contact-shadow",
    src: shadowPath.slice(7),
    kind: "image",
    width: 512,
    height: 128,
    alpha: true,
  };
  assert.equal(Object.keys(assets).length, 83);
  await writeFile(
    "src/projects/ivans-escape/pass02-assets.ts",
    `// Generated by scripts/prepare-ivans-pass02.ts.\nimport type { AssetManifest } from '../../engine/types';\nexport const pass02Assets: AssetManifest = ${JSON.stringify(assets, null, 2)};\n`,
  );
  await writeFile(
    "docs/projects/ivans-escape/redirection/pass02/SOURCE_ART.json",
    JSON.stringify(sources, null, 2),
  );
  console.log(
    `Prepared ${Object.keys(assets).length} pass02 layers; old sources preserved.`,
  );
}
main().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
